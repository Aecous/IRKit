"""Trusted child entrypoint. Model code runs only inside the OS sandbox."""

from __future__ import annotations

import json
import sys
from pathlib import Path

# Executed by absolute file path with -I; import our package from this trusted directory.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from irkit.evidence import iter_records  # noqa: E402
from irkit.store import dumps  # noqa: E402


def transform(config):
    output = Path("rows.jsonl")
    counts = {sid: {"read": 0} for sid in config["sources"]}
    emitted = 0
    with output.open("w", encoding="utf-8") as stream:

        def records(source_id, encoding="utf-8"):
            source = config["sources"][source_id]
            for ordinal, text in iter_records(source["path"], source["record_kind"], encoding):
                counts[source_id]["read"] += 1
                yield ordinal, text

        def emit(fields, refs):
            nonlocal emitted
            if not isinstance(fields, dict) or not isinstance(refs, list) or not refs:
                raise ValueError("emit requires a field object and nonempty raw refs")
            if any(key.startswith("_") for key in fields):
                raise ValueError("Underscore-prefixed fields are reserved")
            emitted += 1
            if emitted > 1_000_000:
                raise ValueError("Run output exceeds one million rows; partition the task")
            stream.write(dumps({**fields, "_refs": refs, "_row_id": emitted}) + "\n")

        namespace = {
            "records": records,
            "emit": emit,
            "SOURCE_IDS": list(config["sources"]),
            "__name__": "__main__",
        }
        exec(compile(Path("transform.py").read_text(), "transform.py", "exec"), namespace)
    Path("metrics.json").write_text(dumps({"source_reads": counts, "emitted": emitted}))


def query(config):
    import duckdb

    con = duckdb.connect(
        config={
            "threads": "2",
            "memory_limit": "1024MB",
            "max_temp_directory_size": "8GB",
            "autoinstall_known_extensions": "false",
            "autoload_known_extensions": "false",
        }
    )
    for dataset_id, path in config["datasets"].items():
        # IDs and paths are generated by trusted storage, never SQL supplied by the model.
        escaped = str(path).replace("'", "''")
        con.execute(f"ATTACH '{escaped}' AS {dataset_id}_db (READ_ONLY)")
        con.execute(f"CREATE VIEW {dataset_id} AS SELECT * FROM {dataset_id}_db.events")
    core_ids = config.get("core_datasets", [])
    for did in core_ids:
        con.execute(f"CREATE VIEW {did}_core AS SELECT * FROM {did}_db.core_events")
    if core_ids and len(core_ids) == len(config["datasets"]):
        core_union = " UNION ALL BY NAME ".join(
            f"SELECT *, '{did}' AS _dataset_id FROM {did}_core" for did in core_ids
        )
        con.execute("CREATE VIEW ir_all_core_events AS " + core_union)
    if config["datasets"]:
        union = " UNION ALL BY NAME ".join(
            f"SELECT *, '{did}' AS _dataset_id FROM {did}" for did in config["datasets"]
        )
        con.execute("CREATE VIEW ir_all_events AS " + union)
    con.execute("SET enable_external_access=false")
    con.execute("SET lock_configuration=true")
    statements = con.extract_statements(config["sql"])
    if len(statements) != 1 or statements[0].type != duckdb.StatementType.SELECT:
        raise ValueError("Exactly one SELECT statement is allowed")
    cursor = con.execute(config["sql"])
    original_names = [column[0] for column in cursor.description]
    names, occupied = [], set()
    for name in original_names:
        candidate, suffix = name, 2
        while candidate in occupied:
            candidate = f"{name}__{suffix}"
            suffix += 1
        occupied.add(candidate)
        names.append(candidate)
    saved, truncated = 0, False
    preview = []
    with Path("results.jsonl").open("w") as output:
        while rows := cursor.fetchmany(500):
            for row in rows:
                if saved == config["max_rows"]:
                    truncated = True
                    break
                value = dict(zip(names, row))
                line = dumps(value)
                if len(line.encode()) > 2 * 1024 * 1024:
                    raise ValueError("Result row too large; narrow the query")
                output.write(line + "\n")
                saved += 1
                if len(preview) < 10:
                    preview.append(value)
            if truncated:
                break
    Path("result_meta.json").write_text(
        dumps(
            {
                "saved_rows": saved,
                "truncated": truncated,
                "columns": names,
                "preview": preview,
                "column_mapping": [
                    {"original": original, "output": output}
                    for original, output in zip(original_names, names)
                ],
            }
        )
    )
    con.close()


if __name__ == "__main__":
    config = json.loads(Path(sys.argv[2]).read_text())
    {"transform": transform, "query": query}[sys.argv[1]](config)
